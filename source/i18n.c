lang_t lang_from_system(void) {
    u8 sys = CFG_LANGUAGE_EN;
    CFGU_GetSystemLanguage(&sys);
    switch (sys) {
        case CFG_LANGUAGE_PT: return LANG_PT;
        case CFG_LANGUAGE_ES: return LANG_ES;
        case CFG_LANGUAGE_RU: return LANG_RU;
        case CFG_LANGUAGE_JP: return LANG_JA;
        case CFG_LANGUAGE_FR: return LANG_FR;
        case CFG_LANGUAGE_DE: return LANG_DE;
        case CFG_LANGUAGE_IT: return LANG_IT;
        case CFG_LANGUAGE_NL: return LANG_NL;
        case CFG_LANGUAGE_ZH: return LANG_ZH;
        case CFG_LANGUAGE_KO: return LANG_KO;
        case CFG_LANGUAGE_TW: return LANG_TW;
        default:              return LANG_EN;
    }
}

lang_t lang_parse(const char *code) {
    for (int i = 0; i < LANG_COUNT; i++)
        if (!strcmp(code, LANG_CODE[i])) return (lang_t)i;
    return LANG_AUTO;
}

lang_t lang_current(void) {
    static lang_t system = LANG_AUTO;
    if (g.lang != LANG_AUTO) return g.lang;
    if (system == LANG_AUTO) system = lang_from_system();
    return system;
}

const char *tr(str_t id) {
    const char *s = STR[lang_current()][id];
    return s ? s : STR[LANG_EN][id];   // a missing translation falls back to English
}

// System font region needed to render a language, or -1 for the standard font.
int lang_font_region(lang_t l) {
    switch (l) {
        case LANG_ZH: return CFG_REGION_CHN;
        case LANG_KO: return CFG_REGION_KOR;
        case LANG_TW: return CFG_REGION_TWN;
        default:      return -1;
    }
}
